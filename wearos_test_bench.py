class WearOSStreamEmulator:
    """
    Emulates the real-time Wear OS to companion smartphone ingestion pipeline:
      - Streams realistic Samsung Watch 4 packets into WearOSStreamBuffer.
      - Feeds conditioned 90s windows directly into the MedGemma-Micro 1D-Conformer.
      - Computes end-to-end telemetry: Latency, SQI, Accuracy, and Rejection of Bad Signals.
    """

    def __init__(self, target_model=None, target_fs: int = 25):
        self.simulator = WearOSPPGSimulator(sampling_rate=target_fs)
        self.buffer = WearOSStreamBuffer(window_sec=90, target_fs=25)
        self.model = target_model

    def stream_full_window(
        self,
        condition: int = 0,
        duration_sec: float = 90.0,
        batch_size: int = 25,
        simulate_clock_delay: bool = False,
    ) -> Dict:
        """
        Pushes a full 90-second Wear OS stream through the buffer and measures performance.
        """
        self.buffer.clear()
        t0 = time.perf_counter()

        packet_batches = list(self.simulator.generate_packets(
            condition=condition,
            duration_sec=duration_sec,
            batch_size=batch_size,
        ))

        total_batches = len(packet_batches)
        total_points = sum(len(b) for b in packet_batches)

        for batch in packet_batches:
            self.buffer.push_batch(batch)
            if simulate_clock_delay:
                # Sleep realistic batch interval (~1 second for 25 samples @ 25 Hz)
                time.sleep(len(batch) / self.simulator.fs)

        ingestion_elapsed_ms = (time.perf_counter() - t0) * 1000.0

        # Check buffer readiness
        status = self.buffer.get_status()

        # Extract model window & DSP conditioning
        t_dsp = time.perf_counter()
        conditioned_tensor, quality = self.buffer.get_model_window()
        dsp_elapsed_ms = (time.perf_counter() - t_dsp) * 1000.0

        result = {
            "condition_tested": condition,
            "condition_name": WearOSPPGSimulator.CONDITIONS[condition],
            "total_points": total_points,
            "batches_sent": total_batches,
            "ingestion_time_ms": round(ingestion_elapsed_ms, 2),
            "dsp_conditioning_ms": round(dsp_elapsed_ms, 2),
            "buffer_fill_pct": status.buffer_fill_pct,
            "sqi_score": quality.get("sqi", 0.0),
            "quality_flag": quality.get("quality_flag", "UNKNOWN"),
            "is_usable": quality.get("is_usable", False),
            "conditioned_shape": list(conditioned_tensor.shape),
            "conditioned_mean": round(float(np.mean(conditioned_tensor)), 4),
            "conditioned_std": round(float(np.std(conditioned_tensor)), 4),
        }

        # If model is attached, run inference
        if self.model is not None and quality.get("is_usable", False):
            import torch
            tensor_in = torch.tensor(conditioned_tensor, dtype=torch.float32).unsqueeze(0)
            t_inf = time.perf_counter()
            with torch.no_grad():
                logits, _ = self.model.ppg_encoder(tensor_in)
                probs = torch.softmax(logits, dim=-1)[0]
                pred_idx = int(torch.argmax(probs).item())
            inference_ms = (time.perf_counter() - t_inf) * 1000.0
            result["predicted_idx"] = pred_idx
            result["confidence"] = round(float(probs[pred_idx].item()), 4)
            result["inference_ms"] = round(inference_ms, 2)

        return result


