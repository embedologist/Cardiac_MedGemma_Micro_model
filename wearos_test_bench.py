"""
Wear OS (Samsung Galaxy Watch 4+) PPG Real-World Test Bench & Stream Emulator
=============================================================================
Mimics actual optical photoplethysmography (PPG) data streams generated by
the Samsung BioActive Sensor on Galaxy Watch 4 / 5 / 6 running Wear OS.

Physical & Electrical Sensor Emulation:
  1. Optical DC Baseline: 400,000 – 900,000 raw ADC counts (skin tone / LED drive dependent).
  2. Pulsatile Arterial AC Wave: 2,000 – 12,000 counts (0.5% – 2.0% Perfusion Index).
  3. Hemodynamic Waveform: Steep systolic upstroke, dicrotic notch, diastolic rebound.
  4. Physiological Respiratory Wander: 0.15 – 0.3 Hz sinusoidal thoracic baseline shift.
  5. Motion Artifact Bursts: Wrist tremors and walking cadence (1.5 – 2.5 Hz).
  6. Optical Shot Noise & Thermal Noise: Gaussian noise on photodiode current.
  7. Samsung Privileged Health SDK Status Codes:
       0: VALID_CONTACT (Sensor flush against skin, valid pulse detected)
      -1: DETACHED / LEAD_OFF (Watch taken off wrist, ambient light only)
       1: MOTION_HIGH (High acceleration detected, optical path decoupled)
  8. Bluetooth Low Energy (BLE) Transmission Jitter:
       Batches of 10 to 25 samples arriving every 400ms – 1000ms with nanosecond jitter.
"""

import time
import math
import random
import logging
from typing import List, Tuple, Dict, Optional, Generator
import numpy as np

from wearos_ppg_adapter import (
    WearOSPPGPoint,
    WearOSPacketProtocol,
    WearOSPPGAdapter,
    WearOSStreamBuffer,
)

logger = logging.getLogger("MedGemmaMicro.WearOSTestBench")


class WearOSPPGSimulator:
    """
    High-fidelity physiological and electrical simulator mimicking the Samsung BioActive
    PPG sensor (Galaxy Watch 4/5/6) under diverse clinical and environmental conditions.
    """

    CONDITIONS = {
        0: "Normal Sinus Rhythm",
        1: "Atrial Fibrillation (AFib)",
        2: "Sinus Bradycardia",
        3: "Sinus Tachycardia",
        4: "Premature Ventricular Contractions (PVC)",
        5: "Sensor Detached (Off-Wrist)",
        6: "Severe Motion Artifact",
    }

    def __init__(
        self,
        sampling_rate: int = 25,
        dc_baseline: int = 650_000,
        ac_amplitude: int = 6_500,
    ):
        """
        Args:
            sampling_rate: 25 Hz (standard Wear OS tracking) or 100 Hz (high precision mode)
            dc_baseline: Mean optical DC level (~400,000 to 900,000 counts)
            ac_amplitude: Peak-to-peak pulsatile amplitude (~2,000 to 12,000 counts)
        """
        self.fs = sampling_rate
        self.dc_baseline = dc_baseline
        self.ac_amplitude = ac_amplitude

    def _generate_single_pulse(self, t_pulse: np.ndarray, pulse_width: float) -> np.ndarray:
        """Models the arterial pulse morphology (systolic peak + dicrotic notch + diastolic wave)."""
        # Steep systolic ejection peak
        systolic = np.exp(-((t_pulse - 0.18 * pulse_width) ** 2) / (2 * (0.07 * pulse_width) ** 2))
        # Dicrotic notch and diastolic reflected pressure wave
        diastolic = 0.38 * np.exp(-((t_pulse - 0.48 * pulse_width) ** 2) / (2 * (0.11 * pulse_width) ** 2))
        return systolic + diastolic

    def generate_waveform(
        self,
        condition: int = 0,
        duration_sec: float = 90.0,
        add_motion_spikes: bool = True,
    ) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
        """
        Generates continuous raw ADC counts mimicking Samsung Galaxy Watch 4.
        Returns:
            timestamps_ns: np.ndarray of shape (N,) int64
            raw_adc: np.ndarray of shape (N,) int32
            status_flags: np.ndarray of shape (N,) int32
        """
        num_samples = int(self.fs * duration_sec)
        t = np.linspace(0, duration_sec, num_samples, endpoint=False)
        base_timestamp_ns = int(time.time() * 1e9)

        # 1. Generate Timestamps with realistic BLE clock jitter
        sample_interval_ns = int(1e9 / self.fs)
        jitter_ns = np.random.normal(0, 0.002 * 1e9, num_samples).astype(np.int64)  # ~2ms jitter
        timestamps_ns = base_timestamp_ns + np.arange(num_samples, dtype=np.int64) * sample_interval_ns + jitter_ns
        timestamps_ns = np.sort(timestamps_ns)  # Monotonic guarantee

        # Handle Detached State (Condition 5)
        if condition == 5:
            # Sensor off-wrist: photodiode registers faint ambient flicker, no cardiac pulses
            ambient_flicker = np.random.normal(1200, 80, num_samples)
            raw_adc = ambient_flicker.astype(np.int32)
            status_flags = np.full(num_samples, -1, dtype=np.int32)  # -1 = DETACHED / LEAD_OFF
            return timestamps_ns, raw_adc, status_flags

        # 2. Physiological Baseline Wander (Respiration ~0.22 Hz + Vasomotor Drift ~0.04 Hz)
        # In raw ADC counts, respiration produces ~10,000 - 25,000 counts of swing
        respiration_dc = 18_000 * np.sin(2 * np.pi * 0.22 * t + np.random.uniform(0, math.pi))
        vasomotor_drift = 12_000 * np.sin(2 * np.pi * 0.04 * t)
        dc_profile = self.dc_baseline + respiration_dc + vasomotor_drift

        # 3. Cardiac Rhythm Beat Intervals
        if condition == 0:  # Normal Sinus Rhythm (65-80 BPM)
            target_bpm = np.random.uniform(66, 78)
            rr_intervals = [60.0 / target_bpm + np.random.normal(0, 0.025) for _ in range(int(duration_sec * 2.5))]
        elif condition == 1:  # AFib (Irregularly irregular, chaotic amplitudes, 95-135 BPM)
            mean_bpm = np.random.uniform(100, 125)
            # Chaotic Gamma/Poisson distributed RR intervals
            rr_intervals = np.random.gamma(shape=3.8, scale=(60.0 / mean_bpm) / 3.8, size=int(duration_sec * 3.5)).tolist()
        elif condition == 2:  # Bradycardia (< 55 BPM)
            target_bpm = np.random.uniform(44, 52)
            rr_intervals = [60.0 / target_bpm + np.random.normal(0, 0.02) for _ in range(int(duration_sec * 1.5))]
        elif condition == 3:  # Tachycardia (> 110 BPM)
            target_bpm = np.random.uniform(115, 140)
            rr_intervals = [60.0 / target_bpm + np.random.normal(0, 0.012) for _ in range(int(duration_sec * 3.5))]
        elif condition == 4:  # PVC (Normal rhythm with premature ectopic beats and compensatory pauses)
            target_bpm = 72
            base_rr = 60.0 / target_bpm
            rr_intervals = []
            cur_t = 0.0
            while cur_t < duration_sec + 5:
                if np.random.rand() < 0.14:  # Premature ectopic event
                    rr_intervals.append(base_rr * 0.54)  # Early coupled beat
                    rr_intervals.append(base_rr * 1.46)  # Compensatory pause
                    cur_t += base_rr * 2.0
                else:
                    rr_intervals.append(base_rr + np.random.normal(0, 0.02))
                    cur_t += base_rr
        elif condition == 6:  # Severe Motion Artifact
            target_bpm = 85
            rr_intervals = [60.0 / target_bpm for _ in range(int(duration_sec * 2.5))]
        else:
            rr_intervals = [0.8 for _ in range(int(duration_sec * 2.0))]

        # 4. Construct Pulsatile AC Signal
        ac_signal = np.zeros(num_samples)
        beat_times = np.cumsum(rr_intervals)

        for i, b_time in enumerate(beat_times):
            if b_time >= duration_sec:
                break
            pulse_w = rr_intervals[i] if i < len(rr_intervals) else 0.8
            # In AFib, stroke volume and therefore pulse amplitude fluctuates markedly
            amp_mod = np.random.uniform(0.55, 1.35) if condition == 1 else np.random.uniform(0.92, 1.08)
            pulse_amp = self.ac_amplitude * amp_mod

            idx_start = int(b_time * self.fs)
            idx_end = min(num_samples, idx_start + int(pulse_w * self.fs))
            samples_in_pulse = idx_end - idx_start

            if samples_in_pulse > 0:
                t_pulse = np.linspace(0, pulse_w, samples_in_pulse, endpoint=False)
                wave = pulse_amp * self._generate_single_pulse(t_pulse, pulse_w)
                ac_signal[idx_start:idx_end] += wave

        # 5. Add Wrist Motion Artifacts
        status_flags = np.zeros(num_samples, dtype=np.int32)
        if condition == 6:  # Severe Motion
            # High-amplitude walking motion (1.8 Hz cadence) with optical decouple
            walking_motion = 90_000 * np.sin(2 * np.pi * 1.8 * t) + 40_000 * np.sin(2 * np.pi * 3.6 * t)
            ac_signal += walking_motion
            status_flags[:] = 1  # 1 = MOTION_HIGH
        elif add_motion_spikes:
            # Random intermittent motion bursts (e.g. wrist readjustment)
            for _ in range(np.random.randint(1, 4)):
                burst_center = np.random.uniform(10, duration_sec - 10)
                burst_len = np.random.uniform(1.5, 3.5)
                mask = (t >= burst_center) & (t <= (burst_center + burst_len))
                if np.any(mask):
                    motion_wave = 55_000 * np.sin(2 * np.pi * 2.2 * t[mask])
                    ac_signal[mask] += motion_wave
                    status_flags[mask] = 1  # Mark corrupted segment

        # 6. Photodiode Shot Noise & Thermal Noise
        shot_noise = np.random.normal(0, 350, num_samples)

        # 7. Final Composite Raw ADC Counts
        raw_adc = (dc_profile + ac_signal + shot_noise).astype(np.int32)
        # Ensure non-negative counts within 24-bit ADC limits (0 to 16,777,215)
        raw_adc = np.clip(raw_adc, 0, 16_777_215)

        return timestamps_ns, raw_adc, status_flags

    def generate_packets(
        self,
        condition: int = 0,
        duration_sec: float = 90.0,
        batch_size: int = 25,
    ) -> Generator[List[WearOSPPGPoint], None, None]:
        """
        Yields batches of WearOSPPGPoint mimicking continuous over-the-air streaming
        from Galaxy Watch 4 to a companion smartphone via Wearable Data Layer API.
        """
        t_arr, adc_arr, status_arr = self.generate_waveform(condition, duration_sec)
        total_samples = len(t_arr)

        for start_idx in range(0, total_samples, batch_size):
            end_idx = min(total_samples, start_idx + batch_size)
            batch = [
                WearOSPPGPoint(
                    timestamp_ns=int(t_arr[i]),
                    ppg_green=int(adc_arr[i]),
                    status=int(status_arr[i]),
                )
                for i in range(start_idx, end_idx)
            ]
            yield batch


